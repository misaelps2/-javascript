/*
LOOP - for

O for serve para repetir um bloco de código.
Ele possui três partes:

1. início
2. condição
3. atualização
*/

// O for controla a repetição.
// O i representa o valor atual da repetição.
// O código dentro das chaves é executado a cada volta.

for (let i = 1; i <= 5; i++) {
    console.log(i);
}